constexpr Vec2 clampToMap(Vec2 v) noexcept {
    if (v.x < 0)
        v.x = 0;
    else if (v.x >= Config::MAP_WIDTH)
        v.x = Config::MAP_WIDTH - 1;
    if (v.y < 0)
        v.y = 0;
    else if (v.y >= Config::MAP_HEIGHT)
        v.y = Config::MAP_HEIGHT - 1;
    return v;
}

