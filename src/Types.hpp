    bool active         = false;
    Vec2 pos{};
    TileType type = TileType::LetterP;
    int timer_ms  = 0;

    bool isCollected(int idx) const { return idx >= 0 && idx < LETTER_COUNT && (letter_mask & (1u << idx)) != 0; }
